"""Prepare a solo AP seed for a real play session: audit, identity, bound pack.

A seed with two slots cannot be played alone: one player's Paraglider may sit
behind the other player's Cryonis terminal, leaving a lone player stuck on
the Great Plateau. A play session therefore uses a solo seed generated by the
official runtime (tools/generate_native.py) from the YAML files of players/.

    python tools/play_seed.py <AP_xxx.zip> --content <update/content> --rpx <U-King.rpx>

1. audits the archive: one BOTW slot, manifest hash, one placement per
   location;
2. copies it into .build/play-seeds/<seed>/ (the local server keeps its
   .apsave next to that copy, so progress survives between sessions);
3. opens it in a local AP server and connects as the slot, to read the exact
   session identity (seed, team, slot, DataPackage checksum) and its token;
4. preserves an existing audited analysis.json on resume, builds the pack
   from project sources and explicit dumps, and selects it in play-pack.json.
"""
from __future__ import annotations

import asyncio
import functools
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
os.environ["SKIP_REQUIREMENTS_UPDATE"] = "1"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / ".build/ap-runtime"))

PLAY_SEEDS = ROOT / ".build/play-seeds"
SCOPE = "generated_solo_ap_server"
GAME = "Breath of the Wild"
_ROWS = json.loads((ROOT / "botw_world/data/locations.json").read_text(encoding="utf-8"))
# Every location but the goal, shops apart: they depend on beedle_shop_items
# and stall_shop_items.
PLACEMENTS = sum(1 for row in _ROWS if row["category"] not in ("Goal", "Shop", "Stall"))


def expected_placements(slot_data: dict) -> int:
    from botw_client import shop_catalog, stall_catalog
    return (PLACEMENTS
            + len(shop_catalog.MERCHANTS) * int(slot_data.get("beedle_shop_items", 0))
            + len(stall_catalog.MERCHANTS) * int(slot_data.get("stall_shop_items", 0)))


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def audit_zip(path: Path) -> dict:
    from MultiServer import Context
    with zipfile.ZipFile(path) as archive:
        names = archive.namelist()
        multidata = Context.decompress(archive.read(
            next(name for name in names if name.endswith(".archipelago"))))
        manifests = [json.loads(archive.read(name)) for name in names
                     if name.endswith(".apbotw.json")]
    if len(manifests) != 1 or len(multidata["locations"]) != 1:
        raise ValueError("a solo BOTW seed is expected")
    manifest = manifests[0]
    claimed = manifest.pop("content_sha256")
    payload = json.dumps(manifest, ensure_ascii=False, sort_keys=True,
                         separators=(",", ":")).encode("utf-8")
    if hashlib.sha256(payload).hexdigest() != claimed:
        raise ValueError("wrong slot manifest hash")
    if manifest["seed"] != multidata["seed_name"] or manifest["slot"] != 1:
        raise ValueError("slot manifest inconsistent with the seed")
    placements = len(multidata["locations"][1])
    expected = expected_placements(multidata["slot_data"][1])
    if placements != expected:
        raise ValueError(f"{placements} placements, {expected} expected")
    return {"seed": multidata["seed_name"], "slots": {"1": manifest["slot_name"]},
            "placements": placements,
            "world_schema": multidata["slot_data"][1].get("world_schema")}


async def identify(path: Path, slot_name: str) -> dict:
    import websockets
    from MultiServer import server
    from botw_client.protocol import ArchipelagoClient
    from botw_client.session import session_token
    from tools.ap_local_server import make_context
    context = make_context(path)
    async with websockets.serve(functools.partial(server, ctx=context),
                                "127.0.0.1", 0) as listener:
        address = f"127.0.0.1:{listener.sockets[0].getsockname()[1]}"
        client = ArchipelagoClient(address, slot_name, game=GAME, log=lambda _: None)
        try:
            await client.connect()
            await client.data_package_event.wait()
            if client.slot != 1 or client.received_items:
                raise ValueError("unexpected solo slot, or already served")
            identity = (client.seed_name, client.team, client.slot,
                        client.data_package_checksum)
        finally:
            await client.close()
    return {"seed": identity[0], "team": identity[1], "slot": identity[2],
            "data_package_checksum": identity[3], "token": session_token(identity)}


def prepare(source: Path, *, content: Path, rpx: Path) -> tuple[Path, Path]:
    audit = audit_zip(source)
    folder = PLAY_SEEDS / audit["seed"]
    archive = folder / source.name
    folder.mkdir(parents=True, exist_ok=True)
    if archive.exists():
        if sha(archive) != sha(source):
            raise ValueError(f"another archive is already there for this seed: {archive}")
    else:
        shutil.copy2(source, archive)
    report = folder / "analysis.json"
    from tools.build_pack_from_source import build, load_seed
    from tools.play_pack import select_pack
    if report.exists():
        binding = load_seed(report, 1)
        if binding["archive_sha256"] != sha(archive) or binding["seed"] != audit["seed"]:
            raise ValueError("existing analysis differs from the seed")
    else:
        identity = asyncio.run(identify(archive, audit["slots"]["1"]))
        data = {"schema": 1, "status": "passed", "scope": SCOPE,
                "archive": str(archive), "archive_sha256": sha(archive),
                "audit": audit, "delivery": {"sessions": {"1": identity}}}
        report.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    pack = build(content, rpx, report, 1, ROOT / ".build/packs-from-source",
                 resource_gate=True, event_gate=True)
    select_pack(folder, pack)
    return report, pack


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("zip", type=Path)
    parser.add_argument("--content", type=Path, required=True)
    parser.add_argument("--rpx", type=Path, required=True)
    arguments = parser.parse_args()
    report, pack = prepare(arguments.zip.resolve(), content=arguments.content, rpx=arguments.rpx)
    print(report)
    print(pack)
